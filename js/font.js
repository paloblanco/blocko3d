// Draws text with fillRect calls; returns the x after the last glyph.
export function drawText(ctx, str, x, y, color) {
  ctx.fillStyle = color;
  let cx = x;
  for (const ch of String(str)) {
    if (ch === '\n') { cx = x; y += 6; continue; }
    const g = G[ch.toUpperCase()] || G['?'];
    for (let i = 0; i < 15; i++) if (g[i] === '1') ctx.fillRect(cx + (i % 3), y + ((i / 3) | 0), 1, 1);
    cx += 4;
  }
  return cx;
}
